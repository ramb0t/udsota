#!/usr/bin/env python3
"""Regenerates test/fixtures/delta_fixtures.h, the delta-download fixtures for the C host test, from
client/tests/demo_server.delta_pair(). Needs the client and detools (pip install ./client[diff]); CI only reads the
output.

    python tools/make_delta_fixtures.py
"""
import argparse
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path[:0] = [str(ROOT / "client"), str(ROOT / "client" / "tests")]
import demo_server              # noqa: E402  (after the path)
from udsota import delta        # noqa: E402


# One C array definition of data, 16 bytes a line.
def c_array(name, data):
    lines = ["    " + " ".join("0x%02x," % b for b in data[i:i + 16]) for i in range(0, len(data), 16)]
    return "static const uint8_t %s[%d] = {\n%s\n};\n" % (name, len(data), "\n".join(lines))


# Writes the fixtures; see the module docstring.
def main():
    argparse.ArgumentParser(description=__doc__.splitlines()[0]).parse_args()
    base, new = demo_server.delta_pair()
    pnone = delta.make_patch(base, new, "none")
    p30 = delta.deflate(pnone)
    body = [
        "/* Generated by tools/make_delta_fixtures.py from client/tests/demo_server.delta_pair(); do not edit.\n"
        " * A base and a new demo image (build_image's layout: one segment, checksum, appended SHA-256) and the\n"
        " * patch between them in esp_delta_ota's format: DELTA_PNONE (uncompressed) and DELTA_P30 (DELTA_PNONE\n"
        " * as raw DEFLATE, what DFI 0x30 carries). DELTA_BASE_HASH is the base's appended SHA-256. */\n",
        "#pragma once\n#include <stdint.h>\n\n",
        c_array("DELTA_BASE", base), c_array("DELTA_NEW", new), c_array("DELTA_BASE_HASH", delta.validation_hash(base)),
        c_array("DELTA_PNONE", pnone), c_array("DELTA_P30", p30),
    ]
    (ROOT / "test" / "fixtures" / "delta_fixtures.h").write_text("".join(body[:2]) + "\n".join(body[2:]))
    print("base %d, new %d; uncompressed patch %d, 0x30 %d bytes" % (len(base), len(new), len(pnone), len(p30)))


if __name__ == "__main__":
    main()
