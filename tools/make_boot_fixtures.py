#!/usr/bin/env python3
"""Regenerates test/fixtures/boot_fixtures.h, a bare image stamped by the client's own udsota.image.stamp(), for the
bootloader core's C test (test/test_udsota_boot_pure.c), which checks the core's CRC and image rules accept it and
that UDSOTA_IMAGE_HEADER lays out the same header. client/tests/test_udsota.py fails when the committed file differs
from what this writes.

    python tools/make_boot_fixtures.py
"""
import argparse
import pathlib
import struct
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
OUT = ROOT / "test" / "fixtures" / "boot_fixtures.h"

# The image's identity, udsota's example one, and its shape: the header past a vector table, and a length that is
# not a multiple of 4, so stamping pads it.
HEADER_OFFSET, SIZE = 0x100, 2050
HW_ID, LAYOUT_ID, REQ_ID, RESP_ID = 1, 1, 0x710, 0x718
VERSION, PRODUCT = "1.0.0", "example"   # a clean X.Y.Z: the descriptor's release flag is set


# The image as a firmware build leaves it: a byte pattern with the header UDSOTA_IMAGE_HEADER places at
# HEADER_OFFSET (magic, version, flags 0, the descriptor, version and project; 0xFF elsewhere), then stamped.
def image():
    from udsota import image as img_mod
    data = bytearray((i * 7 + 13) & 0xFF for i in range(SIZE))
    hdr = bytearray(b"\xff" * img_mod.BARE_HDR_LEN)
    struct.pack_into("<IHH", hdr, 0, img_mod.BARE_HDR_MAGIC, img_mod.BARE_HDR_VERSION, 0)
    blk = img_mod.BARE_HDR_DESC_OFFSET
    hdr[blk:blk + img_mod.BARE_IMAGE_ID_OFFSET] = bytes(img_mod.BARE_IMAGE_ID_OFFSET)
    struct.pack_into("<IHBBHHB", hdr, blk, img_mod.DESC_MAGIC, 1, HW_ID, LAYOUT_ID, REQ_ID, RESP_ID, 0x01)
    hdr[blk + img_mod.BARE_VERSION_OFFSET:blk + img_mod.BARE_VERSION_OFFSET + len(VERSION)] = VERSION.encode()
    hdr[blk + img_mod.BARE_PROJECT_OFFSET:blk + img_mod.BARE_PROJECT_OFFSET + len(PRODUCT)] = PRODUCT.encode()
    data[HEADER_OFFSET:HEADER_OFFSET + len(hdr)] = hdr
    return img_mod.stamp(bytes(data), HEADER_OFFSET)


# One C array definition of data, 16 bytes a line.
def c_array(name, data):
    lines = ["    " + " ".join("0x%02x," % b for b in data[i:i + 16]) for i in range(0, len(data), 16)]
    return "static const uint8_t %s[%d] = {\n%s\n};\n" % (name, len(data), "\n".join(lines))


# The header file's text.
def render():
    data = image()
    return "".join([
        "/* Generated by tools/make_boot_fixtures.py with the client's udsota.image.stamp(); do not edit.\n"
        " * BOOT_IMAGE: a bare image of BOOT_IMAGE_SIZE bytes, padded and stamped, with its header at\n"
        " * BOOT_IMAGE_HEADER_OFFSET and the identity below. */\n",
        "#pragma once\n#include <stdint.h>\n\n",
        "#define BOOT_IMAGE_HEADER_OFFSET 0x%Xu\n" % HEADER_OFFSET,
        "#define BOOT_IMAGE_HW_ID         %du\n" % HW_ID,
        "#define BOOT_IMAGE_LAYOUT_ID     %du\n" % LAYOUT_ID,
        "#define BOOT_IMAGE_REQ_ID        0x%03Xu\n" % REQ_ID,
        "#define BOOT_IMAGE_RESP_ID       0x%03Xu\n" % RESP_ID,
        "#define BOOT_IMAGE_VERSION       \"%s\"\n" % VERSION,
        "#define BOOT_IMAGE_PRODUCT       \"%s\"\n" % PRODUCT,
        "#define BOOT_IMAGE_SIZE          %du\n\n" % len(data),
        c_array("BOOT_IMAGE", data),
    ])


# Writes the fixture; see the module docstring.
def main():
    argparse.ArgumentParser(description=__doc__.splitlines()[0]).parse_args()
    OUT.write_text(render())
    print("wrote %s" % OUT.relative_to(ROOT))


if __name__ == "__main__":
    sys.path.insert(0, str(ROOT / "client"))   # imported by the client's tests, it takes their udsota instead
    main()
